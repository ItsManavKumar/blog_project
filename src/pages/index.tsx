function RecentBlogs() {
  const {
    data,
    fetchNextPage,
    hasNextPage,
    isLoading,
    isError,
  } = api.tweet.infiniteFeed.useInfiniteQuery(
    {},
    {
      getNextPageParam: (lastPage) => lastPage.nextCursor,
    }
  );

  return (
    <InfiniteTweetList
      tweets={data?.pages.flatMap((page) => page.tweets) ?? []}
      fetchNextPage={fetchNextPage}
      hasMore={hasNextPage ?? false}
      isLoading={isLoading}
      isError={isError}
    />
  );
}

